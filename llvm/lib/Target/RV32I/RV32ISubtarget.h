#ifndef LLVM_LIB_TARGET_RV32I_RV32ISUBTARGET_H
#define LLVM_LIB_TARGET_RV32I_RV32ISUBTARGET_H

#include "RV32IFrameLowering.h"
#include "RV32IISelLowering.h"
#include "RV32IInstrInfo.h"
#include "RV32IRegisterInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/Target/TargetMachine.h"

#define GET_SUBTARGETINFO_HEADER
#include "RV32IGenSubtargetInfo.inc"

namespace llvm {

class RV32ISubtarget : public RV32IGenSubtargetInfo {
public:
  RV32ISubtarget(const Triple &TT, StringRef CPU, StringRef TuneCPU, StringRef FS,
                 const TargetMachine &TM);

  // Parses the feature string.  The definition is generated by TableGen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  RV32ISubtarget &initializeSubtargetDependencies(StringRef CPU,
                                                  StringRef TuneCPU,
                                                  StringRef FS);

  const RV32IInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const RV32IRegisterInfo *getRegisterInfo() const override { return &RegInfo; }
  const RV32IFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const RV32ITargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  bool enableMachineScheduler() const override { return true; }

private:
  RV32IFrameLowering FrameLowering;
  RV32IInstrInfo InstrInfo;
  RV32IRegisterInfo RegInfo;
  RV32ITargetLowering TLInfo;
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_RV32I_RV32ISUBTARGET_H
